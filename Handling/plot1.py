import matplotlib.pyplot as plt
import numpy as np

# กำหนดสไตล์ภาพรวมและขนาดหน้าต่างพล็อตให้มีขนาดใหญ่พอสำหรับ 3x3 Panels
fig, axs = plt.subplots(3, 3, figsize=(16, 14))
fig.patch.set_facecolor('#f0f0f0')  # สีพื้นหลังรอบนอกคล้ายรูปตัวอย่าง

# =========================================================================
# [แถวที่ 1, คอลัมน์ 1] - กราฟกระจายจุด (Matplotlib Scatter Plot)
# =========================================================================
ax1 = axs[0, 0]
np.random.seed(42)
x1 = np.random.randint(0, 100, 100)
y1 = np.random.randint(0, 100, 100)
colors1 = np.random.randint(0, 100, 100)
# ใช้ Colormap แบบ 'Accent' หรือใกล้เคียงเพื่อแบ่งเฉดสีจำกัดตามต้นฉบับ W3Schools
scatter1 = ax1.scatter(x1, y1, c=colors1, cmap='Accent', s=40)
ax1.set_xlim(-5, 105)
ax1.set_ylim(-5, 105)
# สร้าง Colorbar ทางด้านขวาเฉพาะช่อง
cbar1 = fig.colorbar(scatter1, ax=ax1, ticks=[0, 20, 40, 60, 80])

# =========================================================================
# [แถวที่ 1, คอลัมน์ 2] - กราฟฟองสบู่โปร่งแสง (Matplotlib Bubble Chart)
# =========================================================================
ax2 = axs[0, 1]
x2 = np.random.randint(0, 100, 100)
y2 = np.random.randint(0, 100, 100)
colors2 = np.random.randint(0, 100, 100)
sizes2 = 10 * np.random.randint(10, 100, 100)
# ใช้ alpha=0.5 เพื่อความโปร่งแสงซ้อนทับกันตามโมเดล
scatter2 = ax2.scatter(x2, y2, c=colors2, s=sizes2, alpha=0.5, cmap='nipy_spectral')
ax2.set_xlim(-5, 105)
ax2.set_ylim(-5, 105)
cbar2 = fig.colorbar(scatter2, ax=ax2, ticks=[0, 20, 40, 60, 80])

# =========================================================================
# [แถวที่ 1, คอลัมน์ 3] - กราฟแท่งแนวนอน (Matplotlib Horizontal Bars)
# =========================================================================
ax3 = axs[0, 2]
categories = ['A', 'B', 'C', 'D']
values = [3, 8, 1, 10]
ax3.barh(categories, values, height=0.2) # ปรับความหนาแท่งให้เรียวบางตามต้นฉบับ
ax3.set_xlim(0, 10.5)

# =========================================================================
# [แถวที่ 2, คอลัมน์ 1] - กราฟเส้นพร้อมกริดสีเขียว (Sports Watch Data)
# =========================================================================
ax4 = axs[1, 0]
x4 = np.array([80, 90, 100, 110, 120, 125])
y4 = np.array([240, 260, 280, 300, 320, 330])
ax4.plot(x4, y4)
ax4.set_title("Sports Watch Data")
ax4.set_xlabel("Average Pulse")
ax4.set_ylabel("Calorie Burnage")
# ตั้งค่าเส้นกริดสีเขียวสลับจุดไข่ปลาตามแบบฝึกหัด W3Schools
ax4.grid(color='green', linestyle='--', linewidth=0.5)

# =========================================================================
# [แถวที่ 2, คอลัมน์ 2] - กราฟเส้นคู่ตัดกัน (Matplotlib Multi-Line)
# =========================================================================
ax5 = axs[1, 1]
x5 = np.array([0, 1, 2, 3])
y5_line1 = np.array([3, 8, 1, 10])
y5_line2 = np.array([6, 2, 7, 11])
ax5.plot(x5, y5_line1)
ax5.plot(x5, y5_line2)

# =========================================================================
# [แถวที่ 2, คอลัมน์ 3] - กราฟเส้นเดี่ยวจุดมาร์กเกอร์แดงใหญ่ (Line Markers)
# =========================================================================
ax6 = axs[1, 2]
x6 = np.array([0, 1, 2, 3])
y6 = np.array([3, 8, 1, 10])
# 'o' คือลักษณะจุดวงกลม, ms=15 ขนาดใหญ่พิเศษ, mec คือขอบจุดสีน้ำเงิน
ax6.plot(x6, y6, marker='o', ms=15, mfc='r')

# =========================================================================
# [แถวที่ 3, คอลัมน์ 1] - กราฟฮิสโตแกรมความถี่ (Matplotlib Histogram)
# =========================================================================
ax7 = axs[2, 0]
# จำลองชุดข้อมูลสุ่มแบบการกระจายปกติรอบค่า 170
x7 = np.random.normal(170, 10, 250)
ax7.hist(x7, bins=10)

# =========================================================================
# [แถวที่ 3, คอลัมน์ 2] - กราฟวงกลมแยกชิ้นส่วนแรก (Pie Chart Exploded)
# =========================================================================
ax8 = axs[2, 1]
y8 = np.array([35, 25, 25, 15])
mylabels8 = ["Apples", "Bananas", "Cherries", "Dates"]
myexplode8 = [0.2, 0, 0, 0] # ดึงชิ้นส่วนแอปเปิ้ลแยกออกห่างวงกลมหลัก
ax8.pie(y8, labels=mylabels8, explode=myexplode8)

# =========================================================================
# [แถวที่ 3, คอลัมน์ 3] - กราฟวงกลมพร้อมคำอธิบายแบบกลุ่ม (Pie Chart with Legend)
# =========================================================================
ax9 = axs[2, 2]
y9 = np.array([35, 25, 25, 15])
mylabels9 = ["Apples", "Bananas", "Cherries", "Dates"]
ax9.pie(y9, labels=mylabels9, labeldistance=1.1)
# ใส่กล่องอธิบาย Legend ที่ตำแหน่งมุมขวาบนของช่องย่อย
ax9.legend(title="Four Fruits:", loc="upper right", bbox_to_anchor=(1.2, 1.15))

# จัดตำแหน่งองค์ประกอบย่อยๆ ให้มีความกระชับและไม่ซ้อนทับกัน
plt.tight_layout()

# สั่งแสดงผลหน้าจอพล็อตออกมา
plt.show()
